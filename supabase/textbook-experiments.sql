create table if not exists public.textbook_experiments (
  id text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  sort_order integer not null default 0,
  is_published boolean not null default true,
  content jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint textbook_experiments_content_shape check (coalesce(
    jsonb_typeof(content) = 'object'
    and content ->> 'id' = id
    and content ->> 'type' in ('experiment', 'general')
    and jsonb_typeof(content -> 'sections') = 'array', false)),
  constraint textbook_experiments_content_size check (octet_length(content::text) <= 262144)
);

create index if not exists textbook_experiments_published_order_idx
  on public.textbook_experiments (sort_order, id) where is_published;

alter table public.textbook_experiments enable row level security;
revoke all on public.textbook_experiments from public, anon, authenticated;
grant select on public.textbook_experiments to anon, authenticated;
grant all on public.textbook_experiments to service_role;

drop policy if exists "read published textbook experiments" on public.textbook_experiments;
create policy "read published textbook experiments" on public.textbook_experiments
  for select to anon, authenticated using (is_published = true);

create or replace function public.touch_textbook_experiment_updated_at()
returns trigger language plpgsql set search_path = pg_catalog as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists textbook_experiments_updated_at on public.textbook_experiments;
create trigger textbook_experiments_updated_at before update on public.textbook_experiments
  for each row execute function public.touch_textbook_experiment_updated_at();

