/** Мөр нь "товчлуур" (W A S D, Esc, ⇧ …) эсэх. Кирилл үсэг орсон бол энэ нь хөдөлгөөний тайлбар ("Зүүн чирэх", "Хулгана") */
export function isKeyInput(input: string): boolean {
  return !/[А-Яа-яӨөҮүЁё]/.test(input);
}

/** Товчлуурын мөрийг хэсэг хэсгээр нь хуваана ("W A / ↑" → ["W","A","/","↑"]) */
export function keyParts(input: string): string[] {
  return input.split(' ').filter(Boolean);
}

/** Үйлдэл бүрт тохирох жижиг дүрс. Эхэлж таарсан дүрмийг авна; таарахгүй бол "▸" */
const ICON_RULES: readonly [RegExp, string][] = [
  [/Алхах/, '🚶'],
  [/Эргэн харах/, '👀'],
  [/Ойроос|ойртуулах/, '🔍'],
  [/Харилцах|авах/, '✋'],
  [/асгах|савлах|Ашиглах/, '🫗'],
  [/Тавих/, '📍'],
  [/Шидэх/, '🎯'],
  [/Гүйх/, '🏃'],
  [/Үсрэх/, '🦘'],
  [/шургуулга/, '🧰'],
  [/тэмдэглэл/, '📝'],
  [/камер|харагдац/, '🎥'],
  [/Хулганыг/, '🖱️'],
  [/Бюрет/, '🧪'],
  [/Esc|Цэс/, '⏸️'],
];

export function iconFor(action: string): string {
  for (const [pattern, icon] of ICON_RULES) if (pattern.test(action)) return icon;
  return '▸';
}
