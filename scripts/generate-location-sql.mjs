import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve('supabase/reference-data');

function readCsv(filename) {
  const source = readFileSync(resolve(root, filename), 'utf8');
  const records = [];
  let row = [];
  let cell = '';
  let quoted = false;

  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    if (quoted && char === '"' && source[index + 1] === '"') {
      cell += '"';
      index += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (!quoted && char === ',') {
      row.push(cell);
      cell = '';
    } else if (!quoted && (char === '\n' || char === '\r')) {
      if (char === '\r' && source[index + 1] === '\n') index += 1;
      row.push(cell);
      if (row.some((value) => value.length > 0)) records.push(row);
      row = [];
      cell = '';
    } else {
      cell += char;
    }
  }
  if (cell.length > 0 || row.length > 0) {
    row.push(cell);
    records.push(row);
  }
  if (quoted) throw new Error(`Unclosed quoted field in ${filename}`);

  const [headers, ...values] = records;
  return values.map((record) => Object.fromEntries(headers.map((header, index) => [header, record[index] ?? ''])));
}

const sqlString = (value) => `'${value.replaceAll("'", "''")}'`;
const aimags = readCsv('aimags.csv');
const soums = readCsv('soums.csv');
const districts = readCsv('ub-districts.csv');
const schools = readCsv('schools.csv');

if (aimags.length !== 21) throw new Error(`Expected 21 aimags, got ${aimags.length}`);
if (districts.length !== 9) throw new Error(`Expected 9 Ulaanbaatar districts, got ${districts.length}`);
if (soums.length !== 330) throw new Error(`Expected 330 rural soums, got ${soums.length}`);
if (aimags.some((row) => !row.id || !row.name) || soums.some((row) => !row.id || !row.aimag_id || !row.name)) {
  throw new Error('Aimag or soum reference row has an empty required field');
}
if (schools.some((row) => !row.name || !row.esis_id || !['rural', 'ulaanbaatar'].includes(row.region_type)
  || (row.region_type === 'rural' && !row.aimag_id)
  || (row.region_type === 'ulaanbaatar' && !row.district_id))) {
  throw new Error('School data has missing identity or location fields');
}

const lines = [
  '-- Generated by scripts/generate-location-sql.mjs from supabase/reference-data/*.csv.',
  '-- Administrative divisions: Open Admin Data Mongolia, CC-BY-4.0; see README.md.',
  'insert into public.aimags(id, name) values',
  aimags.map((row) => `  (${sqlString(row.id)}, ${sqlString(row.name)})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name;',
  '',
  'insert into public.ub_districts(id, name) values',
  districts.map((row) => `  (${sqlString(row.id)}, ${sqlString(row.name)})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name;',
  '',
  'insert into public.soums(id, aimag_id, name) values',
  soums.map((row) => `  (${sqlString(row.id)}, ${sqlString(row.aimag_id)}, ${sqlString(row.name)})`).join(',\n'),
  'on conflict (id) do update set aimag_id = excluded.aimag_id, name = excluded.name;',
  '',
  '-- schools.csv is normalized from the official ESIS school-directory JSON.',
  'insert into public.schools(name, region_type, district_id, aimag_id, soum_id, is_sample, esis_id) values',
  schools.map((row) => `  (${sqlString(row.name)}, ${sqlString(row.region_type)}, ${row.district_id ? sqlString(row.district_id) : 'null'}, ${row.aimag_id ? sqlString(row.aimag_id) : 'null'}, ${row.soum_id ? sqlString(row.soum_id) : 'null'}, ${row.is_sample === 'true'}, ${sqlString(row.esis_id)})`).join(',\n'),
  'on conflict (esis_id) where esis_id is not null do update set name = excluded.name, region_type = excluded.region_type, district_id = excluded.district_id, aimag_id = excluded.aimag_id, soum_id = excluded.soum_id, is_sample = false;',
  '',
];

writeFileSync(resolve(root, 'reference-data.seed.sql'), lines.join('\n'));
console.log(`Generated seed SQL for ${districts.length} districts, ${aimags.length} aimags, ${soums.length} soums, and ${schools.length} official schools.`);
