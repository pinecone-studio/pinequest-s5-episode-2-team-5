import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const packs = await Promise.all([
  readFile(new URL('src/data/revision-hub/g8-chem/content.json', root), 'utf8'),
  readFile(new URL('src/data/revision-hub/g9-chem/content.json', root), 'utf8'),
]);
for (const [index, pack] of packs.entries()) {
  const parsed = JSON.parse(pack);
  const expectedGrade = index + 8;
  if (parsed.meta?.grade !== expectedGrade || !parsed.meta?.id) throw new Error(`Expected the canonical Grade ${expectedGrade} chemistry pack`);
  if (pack.includes('$revision_hub_pack$')) throw new Error('SQL literal delimiter appears in revision pack');
}

const migration = await readFile(new URL('supabase/migrations/202610250001_grade8_hub.sql', root), 'utf8');
const sql = `-- Generated by npm run grade8:sql. Paste this entire file into Supabase SQL Editor and Run.
-- Adds the revision hub schema and saves the existing Grade 8 and Grade 9 content packs.
begin;

${migration}

insert into hub.content_packs (pack_id, content)
select seed.pack_id, seed.content
from jsonb_to_recordset($revision_hub_packs$
${JSON.stringify(packs.map((pack) => {
  const content = JSON.parse(pack);
  return { pack_id: content.meta.id, content };
}), null, 2)}
$revision_hub_packs$::jsonb) as seed(pack_id text, content jsonb)
on conflict (pack_id) do update set content = excluded.content, updated_at = now();

commit;

select p.id, p.version, p.is_published, c.content -> 'meta' ->> 'title' as title,
       jsonb_array_length(c.content -> 'topics') as topics
from hub.packs p join hub.content_packs c on c.pack_id = p.id
where p.id in ('mn-g8-chemistry', 'g9-chem') order by p.id;
`;

const output = new URL('supabase/grade8-hub.sql', root);
await writeFile(output, sql);
console.log(`Prepared Grade 8 and Grade 9 packs (${packs.reduce((n, pack) => n + Buffer.byteLength(pack), 0)} bytes) in ${output.pathname}`);
