import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseExperiment } from '../openlab-3d/src/lab/experiment-schema.ts';

const root = new URL('../', import.meta.url);
const definitions = JSON.parse(await readFile(new URL('openlab-3d/src/data/experiments.json', root), 'utf8')).map(parseExperiment);
if (new Set(definitions.map((entry) => entry.id)).size !== definitions.length) throw new Error('Duplicate experiment ids');
const migration = await readFile(new URL('supabase/migrations/202610220001_experiments.sql', root), 'utf8');
const rows = definitions.map((content, sort_order) => ({ id: content.id, sort_order, content }));
const json = JSON.stringify(rows, null, 2);
if (json.includes('$openlab_seed$')) throw new Error('SQL literal delimiter appears in catalog');
const sql = `-- Generated by npm run experiments:sql. Paste this entire file into Supabase SQL Editor and Run.
-- Existing rows are preserved, including edits made in the Supabase dashboard.
begin;

${migration}
insert into public.experiments (id, schema_version, sort_order, is_published, content)
select seed.id, 1, seed.sort_order, true, seed.content
from jsonb_to_recordset($openlab_seed$
${json}
$openlab_seed$::jsonb) as seed(id text, sort_order integer, content jsonb)
on conflict (id) do nothing;

commit;

select id, content ->> 'title' as title, is_published from public.experiments order by sort_order, id;
`;
const output = new URL('supabase/experiments.sql', root);
await writeFile(output, sql);
await writeFile(new URL('supabase/elephant-toothpaste.example.json', root), JSON.stringify(definitions.find((entry) => entry.id === 'elephant'), null, 2) + '\n');
console.log(`Prepared ${definitions.length} JSON experiments in ${fileURLToPath(output)}`);
